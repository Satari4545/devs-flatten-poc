"""Automatic fusion via BFS + transition table. Pure code, no LLM.

This DOES produce a fused atomic: no component objects, no loops over
atomics, one ta / one lam / one delta_int. Hazel's literal requirement.

Honest catches:
  1. It enumerated reachable states to build the table -> doesn't scale.
  2. States are meaningless integers (0, 1), not `holder`.
  3. Only complete for closed models: external inputs could reach states
     BFS never saw.

Run: python3 fuse_auto.py  (writes fused_auto_pingpong.py, checks it)
"""
import importlib.util

from pingpong import PingPong
from flatten import dissolve

INF = float("inf")
atomics, edges = dissolve(PingPong())
routes = {}
for s, sp, d, dp in edges:
    routes.setdefault((s, sp), []).append((d, dp))
names = sorted(atomics)


def get_key():
    return tuple((atomics[n].phase, atomics[n].sigma) for n in names)


def set_key(k):
    for n, (ph, sg) in zip(names, k):
        atomics[n].phase, atomics[n].sigma = ph, sg


def one_step():
    dt = min(a.time_advance() for a in atomics.values())
    assert dt != INF
    for a in atomics.values():
        a.sigma -= dt
    imm = [n for n in names if atomics[n].time_advance() == 0]
    outs, bags = [], {}
    for n in imm:
        for p, v in atomics[n].output_function_lambda():
            outs.append((p, (n, v)))
            for d, dp in routes.get((n, p), []):
                bags.setdefault(d, {}).setdefault(dp, []).append(v)
    for n in names:
        a, bag = atomics[n], bags.get(n, {})
        if n in imm and bag:
            a.confluent_transition_function(bag)
        elif n in imm:
            a.internal_transition_function()
        elif bag:
            a.external_transition_function(0.0, bag)
    return outs


def fmt_ta(t):
    return 'INF' if t == INF else repr(t)


# BFS reachable states
init = get_key()
seen = {init: 0}
queue = [init]
while queue:
    set_key(queue.pop(0))
    one_step()
    k = get_key()
    if k not in seen:
        seen[k] = len(seen)
        queue.append(k)

# transition table on the encoded states
table, notes = {}, {}
for k, i in seen.items():
    set_key(k)
    outs = one_step()
    j = seen[get_key()]
    ta = min(sg for _, sg in k)
    table[i] = (ta, outs, j)
    notes[i] = k

src = '''"""Fused ping-pong, generated by fuse_auto.py.

No component objects. No loops over atomics. One time_advance,
one output_function_lambda, one internal_transition_function.
States are integers -- the machine works, but they MEAN nothing.
`holder` (who has the ball) is the insight code could not produce.
"""
INF = float("inf")

# state id -> {"ta", "out", "next"}   (comments: the product state it came from)
'''
src += 'TRANSITIONS = {\n'
for i in sorted(table):
    ta, outs, j = table[i]
    src += f'    {i}: {{"ta": {fmt_ta(ta)}, "out": {outs!r}, "next": {j}}},  # {notes[i]}\n'
src += '''}


class AutoFusedPingPong:
    def __init__(self):
        self.state = 0  # initial global state

    def time_advance(self):
        return TRANSITIONS[self.state]["ta"]

    def output_function_lambda(self):
        return list(TRANSITIONS[self.state]["out"])

    def internal_transition_function(self):
        self.state = TRANSITIONS[self.state]["next"]

    def external_transition_function(self, elapsed_time, input_bag):
        raise NotImplementedError("closed model: table covers reachable states only")

    def confluent_transition_function(self, input_bag):
        raise NotImplementedError("closed model: table covers reachable states only")

    def run(self, hits=10):
        time, trace = 0.0, []
        for _ in range(hits):
            time += self.time_advance()
            trace.extend((round(time, 10), holder, val)
                         for _, (holder, val) in self.output_function_lambda())
            self.internal_transition_function()
        return trace


if __name__ == "__main__":
    for t, src, out in AutoFusedPingPong().run():
        print(f"t={t:g}  {src} !send {out}")
'''

with open("fused_auto_pingpong.py", "w") as f:
    f.write(src)
print("wrote fused_auto_pingpong.py")

# check it
spec = importlib.util.spec_from_file_location("fa", "fused_auto_pingpong.py")
fa = importlib.util.module_from_spec(spec)
spec.loader.exec_module(fa)
got = fa.AutoFusedPingPong().run()
expected = [(round(0.1 * t, 10), "A" if t % 2 == 1 else "B", "ball")
            for t in range(1, 11)]
assert got == expected, got
print("auto-fused trace matches OK")
